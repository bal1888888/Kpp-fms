import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {PGlite} from '@electric-sql/pglite';

const root=new URL('../',import.meta.url);
const migrationUrl=new URL('supabase/migrations/20260911133500_operator_hm_early_reference_guard_v1.sql',root);

test('operator HM is rejected early when below trusted server reference',async()=>{
  const db=new PGlite();
  try{
    await db.exec(`
      create role anon;
      create role authenticated;
      create schema private;
      create table private.test_hm_ref(unit text primary key,hm numeric,source text);
      create function private.kpp_current_hm_reference(p_unit text)
      returns table(hm numeric,source text)
      language sql stable
      as $$ select r.hm,r.source from private.test_hm_ref r where upper(r.unit)=upper(trim(p_unit)) limit 1 $$;
      create table public.operator_unit_checkins(
        id bigint generated by default as identity primary key,
        unit text not null,
        hm_awal numeric,
        hm_actual numeric
      );
    `);
    await db.exec(fs.readFileSync(migrationUrl,'utf8'));
    const q=async(sql,params=[]) => (await db.query(sql,params)).rows;

    await q(`insert into private.test_hm_ref(unit,hm,source) values('TEST-A',100,'trusted')`);
    await assert.rejects(
      ()=>q(`insert into public.operator_unit_checkins(unit,hm_awal) values('TEST-A',99)`),
      /HM referensi server 100/
    );

    const [{id}]=await q(`insert into public.operator_unit_checkins(unit,hm_awal) values('TEST-A',100) returning id`);
    await q(`delete from private.test_hm_ref where unit='TEST-A'`);
    const [{id:id2}]=await q(`insert into public.operator_unit_checkins(unit,hm_awal) values('TEST-B',90) returning id`);
    await q(`insert into private.test_hm_ref(unit,hm,source) values('TEST-B',100,'trusted')`);

    await assert.rejects(
      ()=>q(`update public.operator_unit_checkins set hm_actual=95 where id=$1`,[id2]),
      /HM referensi server 100/
    );
    await q(`update public.operator_unit_checkins set hm_actual=105 where id=$1`,[id2]);
    assert.equal(Number((await q(`select hm_actual from public.operator_unit_checkins where id=$1`,[id2]))[0].hm_actual),105);

    await q(`delete from private.test_hm_ref where unit='TEST-B'`);
    await assert.rejects(
      ()=>q(`update public.operator_unit_checkins set hm_actual=80 where id=$1`,[id2]),
      /lebih kecil dari HM awal 90/
    );

    assert.equal(Number((await q(`select hm_awal from public.operator_unit_checkins where id=$1`,[id]))[0].hm_awal),100);
    const triggers=await q(`select tgname from pg_trigger where tgrelid='public.operator_unit_checkins'::regclass and not tgisinternal`);
    assert.ok(triggers.some(row=>row.tgname==='trg_kpp_operator_hm_reference_guard'));
  } finally {
    await db.close();
  }
});
