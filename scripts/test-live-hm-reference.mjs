const migration = new URL('../supabase/migrations/20261111083000_live_hm_reference.sql', import.meta.url);

test('Admin can verify the latest manual fuel history without allowing stale or anomalous HM', async () => {
  const db = new PGlite();
  try {
    await db.exec(`
      create schema private;
      create schema auth;
      create role anon;
      create role authenticated;
      create function auth.uid() returns uuid language sql as $$select '11111111-1111-4111-8111-111111111111'::uuid$$;
      create function public.current_staff_role() returns text language sql as $$select current_setting('test.staff_role')$$;
      create table unit_master(code_unit text,active boolean);
      insert into unit_master values ('DT7441',true);
      create table operator_unit_checkins(unit text,tanggal date,shift text,status text,fuel_history_id bigint);
      create table ccr_allocations(unit text,tanggal date,shift text,status text);
      create table storage_master(code text,warehouse text,storage_type text,active boolean);
      insert into storage_master values ('FT0075','FT01','FT',true);
      create function private.kpp_storage_wh(text) returns text language sql as $$select $1$$;
      create function public.ccr_operational_timestamp(d date,s text,t time) returns timestamp language sql immutable as $$
        select d+t+case when s='Shift 2' and t<time '06:30' then interval '1 day' else interval '0' end
      $$;
      create table hm_corrections(id bigint generated by default as identity,unit text, tanggal date,jam time,hm numeric);
      create table fuel_history(id bigint generated by default as identity primary key, unit text, tanggal date, jam time, shift integer, operator text, hm_awal numeric, hm_akhir numeric, hm_jalan numeric, fuel numeric, fuel_truck text, wh text, fuelman_name text, duplicate_of_id bigint, hm_ref_excluded boolean default false, hm_ref_excluded_reason text, session_id uuid, ccr_allocation_id bigint, operator_checkin_id bigint);
      create function private.kpp_current_hm_reference(p_unit text) returns table(hm numeric, source text) language sql stable as $$
        select h.hm_akhir,'HM server' from public.fuel_history h where h.unit=p_unit and not h.hm_ref_excluded and h.duplicate_of_id is null order by h.tanggal desc,h.id desc limit 1
      $$;
      create function public.submit_operator_actual_hm(bigint,text,uuid,numeric,timestamptz) returns void language sql as $$select$$;
      create function public.submit_ccr_fueling(bigint,date,time,numeric,text,numeric,uuid) returns void language sql as $$select$$;
      insert into fuel_history(unit,tanggal,hm_awal,hm_akhir,fuel,shift,fuel_truck,hm_ref_excluded)
      values ('DT7441','2025-09-15',3002,3011,100,1,'FT0075',false),
             ('DT7441','2025-11-10',3909,3919,100,1,'FT0075',true),
             ('DT7441','2025-11-09',3901,3909,100,1,'FT0075',true),
             ('DT7441','2025-11-10',3919,39999,100,1,'FT0075',true);
      update fuel_history set jam='07:00:00' where id=4;
      set test.staff_role = 'fuelman';
      set timezone = 'Asia/Jakarta';
    `);
    const sql = fs.readFileSync(migration, 'utf8');
    await db.exec(sql.split('-- CCR actual-HM rollout')[0]);
    await db.exec(sql.slice(sql.indexOf('-- The date on a Shift 2 record')));
    const verify = id => db.query("select public.save_verified_logsheet_hm($1, null, 'DT7441', $2) result", [id, {2:3919,3:3909,4:39999}[id]]);
    await assert.rejects(verify(2), /Admin\/GL/);
    await db.exec("set test.staff_role = 'gl'");
    const result = await verify(2);
    assert.equal(result.rows[0].result.hm,3919);
    assert.equal((await verify(2)).rows[0].result.id,2);
    await assert.rejects(verify(3), /lebih lama|lebih kecil/);
    await assert.rejects(verify(4), /Lonjakan/);
    const rows = await db.query('select id, hm_ref_excluded from fuel_history order by id');
    assert.deepEqual(rows.rows.map(r=>r.hm_ref_excluded), [false,false,true,true]);
    const save = payload => db.query("select public.save_verified_logsheet_hm(null, $1, 'DT7441', $2) result", [payload,payload.hm_akhir]);
    const payload = {unit:'DT7441', tanggal:'2025-11-11', jam:'06:45:00', shift:1, fuel:120, fuel_truck:'FT0075', hm_akhir:3929};
    await db.exec("insert into ccr_allocations values ('DT7441','2025-11-11','Shift 1','ACTIVE')");
    await assert.rejects(save(payload), /sesi pengisian aktif/);
    await db.exec("delete from ccr_allocations");
    await assert.rejects(save({...payload, fuel_truck:null}), /Fuel Truck aktif/);
    assert.equal((await save({...payload, wh:'salah'})).rows[0].result.hm,3929);
    assert.equal((await db.query('select wh from fuel_history where id=5')).rows[0].wh,'FT01');
    await assert.rejects(db.exec(`insert into fuel_history(unit,tanggal,shift,hm_akhir,fuel,fuel_truck,hm_ref_excluded_reason)
      values ('DT7441','2025-11-11',1,3929,120,'FT0075','Dimasukkan melalui Logsheet Editor; histori manual tidak dipakai sebagai HM reference.')`), /serupa sudah tersimpan/);
    assert.equal((await save(payload)).rows[0].result.id,5);
    await assert.rejects(save({...payload, hm_akhir:4100}), /Lonjakan/);
    assert.equal((await db.query('select count(*)::int n from fuel_history')).rows[0].n,5);
    await db.exec(`insert into unit_master values ('NIGHT01',true);
      insert into fuel_history(unit,tanggal,jam,shift,hm_awal,hm_akhir,fuel,fuel_truck,hm_ref_excluded)
      values ('NIGHT01','2025-11-11','21:00',2,490,500,100,'FT0075',false),
             ('NIGHT01','2025-11-11','02:00',2,500,505,100,'FT0075',true)`);
    const night = await db.query(`select public.save_verified_logsheet_hm(
      (select id from fuel_history where unit='NIGHT01' and hm_akhir=505),null,'NIGHT01',505) result`);
    assert.equal(night.rows[0].result.hm,505);
    const baseline = await db.query("select hm,valid from private.kpp_ccr_last_fueling_baseline('NIGHT01')");
    assert.equal(Number(baseline.rows[0].hm),505);
    assert.equal(baseline.rows[0].valid,true);
  } finally { await db.close(); }
});

test('CCR keeps the planned HM and Fuelman records the actual HM from the linked check-in exactly once', async () => {
  const db = new PGlite();
  try {
    await db.exec(fs.readFileSync(new URL('fixtures/operator-hm-schema.sql', import.meta.url),'utf8'));
    await db.exec(`
      create role anon;
      create role authenticated;
      alter table public.operator_unit_checkins add column hm_actual_source text;
      alter table public.unit_master add column fc_standard_lphm numeric, add column quota_tolerance_liter numeric;
      alter table public.fuel_history add column duplicate_of_id bigint, add column operator_checkin_id bigint;
      create table public.hm_corrections(id bigint generated by default as identity,unit text,tanggal date,jam time,hm numeric);
      create table public.storage_master(code text,warehouse text,storage_type text,active boolean);
      insert into public.storage_master values ('FT0075','FT01','FT',true);
      create function private.kpp_storage_wh(text) returns text language sql as $$select $1$$;
      create function private.kpp_shift_is_current(date,text) returns boolean language sql as $$select true$$;
      create function private.kpp_current_hm_reference(p_unit text) returns table(hm numeric,source text)
        language sql stable as $$select max(h.hm_akhir)::numeric,'HM server' from public.fuel_history h
        where h.unit=p_unit and not coalesce(h.hm_ref_excluded,false)$$;
      select set_config('test.uid','11111111-1111-4111-8111-111111111111',false);
      select set_config('test.role','gl',false);
      insert into public.unit_master(code_unit,active,operator_checkin_required,fc_standard_lphm)
        values ('DT7441',true,true,15),('TL01',true,false,null);
      insert into public.unit_checkin_tokens(unit,token) values ('DT7441','22222222-2222-4222-8222-222222222222');
      insert into public.fuel_history(unit,tanggal,hm_akhir,fuel,shift) values ('DT7441','2025-11-10',3919,100,1);
    `);
    await db.exec(fs.readFileSync(migration,'utf8'));
    const q = async (sql,args=[]) => (await db.query(sql,args)).rows;
    const [op]=await q(`select (timezone('Asia/Jakarta',now())::date-case when timezone('Asia/Jakarta',now())::time<time '06:30' then 1 else 0 end)::text as date,
      case when timezone('Asia/Jakarta',now())::time>=time '06:30' and timezone('Asia/Jakarta',now())::time<time '18:30' then 'Shift 1' else 'Shift 2' end as shift`);
    await q(`insert into public.operator_unit_checkins(unit,tanggal,shift,status,hm_awal) values ('DT7441',$1,$2,'ACTIVE',3921)`,[op.date,op.shift]);
    await q(`insert into public.ccr_allocations(unit,tanggal,shift,operator_unit,hm_ccr,hm_taken_time,max_qty,tolerance_qty,status,operator_checkin_id)
      values ('DT7441',$1,$2,'Operator',3927,timezone('Asia/Jakarta',now())::time,120,10,'ACTIVE',1),
      ('TL01',$1,$2,'Petugas',150,timezone('Asia/Jakarta',now())::time,120,10,'ACTIVE',null)`,[op.date,op.shift]);
    const fuel=(id,qty=100)=>q(`select public.submit_ccr_fueling($1,$2,timezone('Asia/Jakarta',now())::time,$3,'FT0075',null,null) result`,[id,op.date,qty]);
    const actual=hm=>q(`select * from public.submit_operator_actual_hm(1,'DT7441','22222222-2222-4222-8222-222222222222',$1,now())`,[hm]);
    await assert.rejects(()=>fuel(1),/Menunggu HM Aktual Operator/);
    await q(`update public.operator_unit_checkins set hm_actual=3927,hm_actual_at=now(),hm_actual_source='CCR',status='READY' where id=1`);
    await assert.rejects(()=>fuel(1),/Menunggu HM Aktual Operator/);
    await assert.rejects(()=>actual(39999),/72 jam/);
    await actual(3929);
    assert.equal((await q('select hm_actual_source from public.operator_unit_checkins where id=1'))[0].hm_actual_source,'OPERATOR');
    await q(`update public.fuel_history set hm_akhir=3930 where id=1`);
    await assert.rejects(()=>fuel(1),/patokan server terbaru/);
    await actual(3931);
    await assert.rejects(()=>fuel(1,131),/melebihi batas/);
    const [{result}]=await fuel(1);
    assert.equal(result.hm_input_ccr,3927);
    assert.equal(result.hm_actual,3931);
    assert.equal(result.hm_previous,3930);
    assert.equal((await q('select status from public.operator_unit_checkins where id=1'))[0].status,'FUELED');
    await assert.rejects(()=>fuel(1),/sudah digunakan|tidak ACTIVE/);
    assert.equal((await q('select count(*)::int n from public.fuel_history where ccr_allocation_id=1'))[0].n,1);
    assert.equal((await fuel(2))[0].result.hm_actual,150);
  } finally { await db.close(); }
});
