create function public.ccr_shift_end_local(p_tanggal date,p_shift text) returns timestamp language sql immutable as $$ select case when p_shift='Shift 1' then p_tanggal::timestamp+time '18:30' when p_shift='Shift 2' then (p_tanggal+1)::timestamp+time '06:30' end $$;
create function public.ccr_operational_timestamp(p_date date,p_shift text,p_time time) returns timestamp language sql immutable as $$ select p_date::timestamp+p_time+case when p_shift='Shift 2' and p_time<time '06:30' then interval '1 day' else interval '0' end $$;
