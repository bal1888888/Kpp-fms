create or replace function public.lubricant_create_storage(p_code text,p_name text,p_storage_type text) returns jsonb
language plpgsql security definer set search_path='' as $$
declare v_role text:=coalesce(public.current_staff_role(),''); v_code text:=upper(trim(coalesce(p_code,''))); v_name text:=trim(coalesce(p_name,'')); v_type text:=upper(trim(coalesce(p_storage_type,''))); v_storage public.lubricant_storages%rowtype;
begin
 if auth.uid() is null or v_role not in ('gl','admin','atasan') then raise exception 'Akun tidak diizinkan membuat storage oli.' using errcode='42501'; end if;
 if v_code='' or v_name='' then raise exception 'Kode dan nama storage wajib diisi.'; end if;
 if v_type not in ('LO','LUBE_SKID') then raise exception 'Tipe storage harus LO atau LUBE_SKID.'; end if;
 insert into public.lubricant_storages(code,name,storage_type,active) values(v_code,v_name,v_type,true)
 on conflict(code) do update set name=excluded.name,storage_type=excluded.storage_type,active=true,updated_at=now() returning * into v_storage;
 insert into public.lubricant_storage_compartments(storage_id,product_id,label,capacity,measurement_type,active)
 select v_storage.id,p.id,coalesce(p.alias,p.name),case when v_type='LO' then 2400 else 1000 end,case when v_type='LO' then 'LO_TERA' else 'LUBE_BAR' end,true
 from public.lubricant_products p where p.active=true and p.default_mobile_compartment=true and p.category='OIL'
 on conflict(storage_id,product_id) do update set label=excluded.label,capacity=excluded.capacity,measurement_type=excluded.measurement_type,active=true;
 insert into public.lubricant_stock_balances(storage_id,product_id,quantity)
 select v_storage.id,p.id,0 from public.lubricant_products p where p.active=true and p.default_mobile_compartment=true and p.category='OIL' on conflict(storage_id,product_id) do nothing;
 return jsonb_build_object('ok',true,'storage',to_jsonb(v_storage));
end;$$;

create or replace function public.lubricant_receive_yard(p_request_id uuid,p_product_code text,p_packaging text,p_package_count numeric,p_quantity numeric,p_supplier text,p_document_no text,p_note text) returns jsonb
language plpgsql security definer set search_path='' as $$
declare v_role text:=coalesce(public.current_staff_role(),''); v_product public.lubricant_products%rowtype; v_yard public.lubricant_storages%rowtype; v_existing public.lubricant_movements%rowtype; v_qty numeric; v_pack text:=upper(trim(coalesce(p_packaging,''))); v_count numeric:=coalesce(p_package_count,0); v_pack_size numeric; v_before numeric; v_after numeric; v_name text; v_move public.lubricant_movements%rowtype;
begin
 if auth.uid() is null or v_role not in ('gl','admin','atasan') then raise exception 'Akun tidak diizinkan menerima oli.' using errcode='42501'; end if;
 if p_request_id is null then raise exception 'Request ID wajib.'; end if;
 select * into v_existing from public.lubricant_movements where request_id=p_request_id; if found then return jsonb_build_object('ok',true,'replayed',true,'movement',to_jsonb(v_existing)); end if;
 select * into v_product from public.lubricant_products where upper(code)=upper(trim(p_product_code)) and active=true; if not found then raise exception 'Produk lubricant tidak ditemukan.'; end if;
 select * into v_yard from public.lubricant_storages where code='YARD' and active=true limit 1; if not found then raise exception 'YARD tidak aktif.'; end if;
 if v_product.category='OIL' and v_pack='DRUM' then if v_count<=0 then raise exception 'Jumlah drum wajib lebih dari 0.'; end if; v_pack_size:=v_product.drum_size; v_qty:=round(v_count*v_pack_size,2);
 elsif v_product.category='OIL' and v_pack='IBC' then if v_count<=0 then raise exception 'Jumlah IBC wajib lebih dari 0.'; end if; v_pack_size:=v_product.ibc_size; v_qty:=round(v_count*v_pack_size,2);
 elsif v_pack in ('MANUAL','BULK') then if p_quantity is null or p_quantity<=0 then raise exception 'Qty manual wajib lebih dari 0.'; end if; v_qty:=round(p_quantity,2); v_pack_size:=null; v_count:=null;
 else raise exception 'Packaging tidak sesuai produk.'; end if;
 insert into public.lubricant_stock_balances(storage_id,product_id,quantity) values(v_yard.id,v_product.id,0) on conflict(storage_id,product_id) do nothing;
 perform pg_advisory_xact_lock(hashtextextended('lubricant:'||v_yard.id||':'||v_product.id,0));
 select quantity into v_before from public.lubricant_stock_balances where storage_id=v_yard.id and product_id=v_product.id for update;
 v_after:=v_before+v_qty; update public.lubricant_stock_balances set quantity=v_after,updated_at=now() where storage_id=v_yard.id and product_id=v_product.id;
 select display_name into v_name from public.staff_profiles where user_id=auth.uid() and active=true limit 1;
 insert into public.lubricant_movements(request_id,movement_type,product_id,destination_storage_id,quantity,base_unit,packaging,package_count,package_size,supplier,document_no,note,destination_balance_before,destination_balance_after,created_by,created_by_name,created_by_role)
 values(p_request_id,'RECEIPT',v_product.id,v_yard.id,v_qty,v_product.base_unit,v_pack,v_count,v_pack_size,nullif(trim(coalesce(p_supplier,'')),''),nullif(trim(coalesce(p_document_no,'')),''),nullif(trim(coalesce(p_note,'')),''),v_before,v_after,auth.uid(),v_name,v_role) returning * into v_move;
 return jsonb_build_object('ok',true,'replayed',false,'movement',to_jsonb(v_move));
end;$$;

create or replace function public.lubricant_transfer(p_request_id uuid,p_product_code text,p_destination_code text,p_quantity numeric,p_note text) returns jsonb
language plpgsql security definer set search_path='' as $$
declare v_role text:=coalesce(public.current_staff_role(),''); v_product public.lubricant_products%rowtype; v_source public.lubricant_storages%rowtype; v_dest public.lubricant_storages%rowtype; v_existing public.lubricant_movements%rowtype; v_qty numeric:=round(coalesce(p_quantity,0),2); v_src_before numeric; v_src_after numeric; v_dst_before numeric; v_dst_after numeric; v_name text; v_move public.lubricant_movements%rowtype;
begin
 if auth.uid() is null or v_role not in ('gl','admin','atasan') then raise exception 'Akun tidak diizinkan transfer oli.' using errcode='42501'; end if;
 if p_request_id is null then raise exception 'Request ID wajib.'; end if;
 select * into v_existing from public.lubricant_movements where request_id=p_request_id; if found then return jsonb_build_object('ok',true,'replayed',true,'movement',to_jsonb(v_existing)); end if;
 if v_qty<=0 then raise exception 'Qty transfer wajib lebih dari 0.'; end if;
 select * into v_product from public.lubricant_products where upper(code)=upper(trim(p_product_code)) and active=true and category='OIL'; if not found then raise exception 'Transfer Yard ke LO/Lube Skid hanya untuk produk oli.'; end if;
 select * into v_source from public.lubricant_storages where code='YARD' and active=true limit 1;
 select * into v_dest from public.lubricant_storages where upper(code)=upper(trim(p_destination_code)) and active=true and storage_type in ('LO','LUBE_SKID') limit 1;
 if v_dest.id is null then raise exception 'Storage tujuan LO/Lube Skid tidak ditemukan.'; end if;
 if not exists(select 1 from public.lubricant_storage_compartments c where c.storage_id=v_dest.id and c.product_id=v_product.id and c.active=true) then raise exception 'Compartment produk tidak tersedia di storage tujuan.'; end if;
 insert into public.lubricant_stock_balances(storage_id,product_id,quantity) values(v_source.id,v_product.id,0),(v_dest.id,v_product.id,0) on conflict(storage_id,product_id) do nothing;
 perform pg_advisory_xact_lock(hashtextextended('lubricant:'||least(v_source.id,v_dest.id)||':'||v_product.id,0));
 perform pg_advisory_xact_lock(hashtextextended('lubricant:'||greatest(v_source.id,v_dest.id)||':'||v_product.id,0));
 select quantity into v_src_before from public.lubricant_stock_balances where storage_id=v_source.id and product_id=v_product.id for update;
 select quantity into v_dst_before from public.lubricant_stock_balances where storage_id=v_dest.id and product_id=v_product.id for update;
 if v_src_before<v_qty then raise exception 'Stock YARD tidak cukup. Tersedia % %, diminta % %.',v_src_before,v_product.base_unit,v_qty,v_product.base_unit; end if;
 v_src_after:=v_src_before-v_qty; v_dst_after:=v_dst_before+v_qty;
 update public.lubricant_stock_balances set quantity=v_src_after,updated_at=now() where storage_id=v_source.id and product_id=v_product.id;
 update public.lubricant_stock_balances set quantity=v_dst_after,updated_at=now() where storage_id=v_dest.id and product_id=v_product.id;
 select display_name into v_name from public.staff_profiles where user_id=auth.uid() and active=true limit 1;
 insert into public.lubricant_movements(request_id,movement_type,product_id,source_storage_id,destination_storage_id,quantity,base_unit,note,source_balance_before,source_balance_after,destination_balance_before,destination_balance_after,created_by,created_by_name,created_by_role)
 values(p_request_id,'TRANSFER',v_product.id,v_source.id,v_dest.id,v_qty,v_product.base_unit,nullif(trim(coalesce(p_note,'')),''),v_src_before,v_src_after,v_dst_before,v_dst_after,auth.uid(),v_name,v_role) returning * into v_move;
 return jsonb_build_object('ok',true,'replayed',false,'movement',to_jsonb(v_move));
end;$$;

create or replace function public.lubricant_record_reading(p_storage_code text,p_product_code text,p_reading numeric,p_note text) returns jsonb
language plpgsql security definer set search_path='' as $$
declare v_role text:=coalesce(public.current_staff_role(),''); v_storage public.lubricant_storages%rowtype; v_product public.lubricant_products%rowtype; v_comp public.lubricant_storage_compartments%rowtype; v_system numeric; v_physical numeric; v_low_level numeric; v_low_vol numeric; v_high_level numeric; v_high_vol numeric; v_name text; v_row public.lubricant_stock_readings%rowtype;
begin
 if auth.uid() is null or v_role not in ('gl','admin','atasan') then raise exception 'Akun tidak diizinkan mencatat pembacaan stock oli.' using errcode='42501'; end if;
 if p_reading is null or p_reading<0 then raise exception 'Nilai pembacaan tidak valid.'; end if;
 select * into v_storage from public.lubricant_storages where upper(code)=upper(trim(p_storage_code)) and active=true and storage_type in ('LO','LUBE_SKID') limit 1; if not found then raise exception 'Storage LO/Lube Skid tidak ditemukan.'; end if;
 select * into v_product from public.lubricant_products where upper(code)=upper(trim(p_product_code)) and active=true and category='OIL' limit 1; if not found then raise exception 'Produk oli tidak ditemukan.'; end if;
 select * into v_comp from public.lubricant_storage_compartments where storage_id=v_storage.id and product_id=v_product.id and active=true limit 1; if not found then raise exception 'Compartment produk tidak ditemukan di storage.'; end if;
 select coalesce(quantity,0) into v_system from public.lubricant_stock_balances where storage_id=v_storage.id and product_id=v_product.id; v_system:=coalesce(v_system,0);
 if v_storage.storage_type='LO' then
  if p_reading>140 then raise exception 'Sonding LO maksimal 140 mm sesuai tabel tera.'; end if;
  select level_mm,volume_liter into v_low_level,v_low_vol from public.lubricant_lo_tera where level_mm<=p_reading order by level_mm desc limit 1;
  select level_mm,volume_liter into v_high_level,v_high_vol from public.lubricant_lo_tera where level_mm>=p_reading order by level_mm asc limit 1;
  if v_low_level is null or v_high_level is null then raise exception 'Tabel tera LO tidak mencakup pembacaan ini.'; end if;
  if v_high_level=v_low_level then v_physical:=v_low_vol; else v_physical:=round(v_low_vol+((p_reading-v_low_level)/(v_high_level-v_low_level))*(v_high_vol-v_low_vol),2); end if;
  select display_name into v_name from public.staff_profiles where user_id=auth.uid() and active=true limit 1;
  insert into public.lubricant_stock_readings(storage_id,product_id,reading_type,reading_value,reading_unit,physical_quantity,system_quantity,variance,note,created_by,created_by_name,created_by_role)
  values(v_storage.id,v_product.id,'LO_SOUNDING',p_reading,'MM',v_physical,v_system,round(v_physical-v_system,2),nullif(trim(coalesce(p_note,'')),''),auth.uid(),v_name,v_role) returning * into v_row;
 else
  if p_reading not in (0,200,400,600,800,1000) then raise exception 'Level Lube Skid harus 0/200/400/600/800/1000 L.'; end if;
  v_physical:=p_reading; select display_name into v_name from public.staff_profiles where user_id=auth.uid() and active=true limit 1;
  insert into public.lubricant_stock_readings(storage_id,product_id,reading_type,reading_value,reading_unit,physical_quantity,system_quantity,variance,note,created_by,created_by_name,created_by_role)
