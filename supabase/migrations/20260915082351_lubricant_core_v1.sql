create extension if not exists pgcrypto;

create table if not exists public.lubricant_products (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  alias text,
  category text not null check (category in ('OIL','GREASE')),
  base_unit text not null check (base_unit in ('L','KG')),
  drum_size numeric(12,2),
  ibc_size numeric(12,2),
  default_mobile_compartment boolean not null default false,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint lubricant_products_drum_positive check (drum_size is null or drum_size > 0),
  constraint lubricant_products_ibc_positive check (ibc_size is null or ibc_size > 0)
);

create table if not exists public.lubricant_storages (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  storage_type text not null check (storage_type in ('YARD','LO','LUBE_SKID')),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.lubricant_storage_compartments (
  id bigint generated by default as identity primary key,
  storage_id bigint not null references public.lubricant_storages(id) on delete cascade,
  product_id bigint not null references public.lubricant_products(id),
  label text not null,
  capacity numeric(12,2) not null,
  measurement_type text not null check (measurement_type in ('LO_TERA','LUBE_BAR')),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique(storage_id, product_id),
  constraint lubricant_comp_capacity_positive check (capacity > 0)
);

create table if not exists public.lubricant_lo_tera (
  level_mm numeric(8,2) primary key,
  volume_liter numeric(12,2) not null check (volume_liter >= 0)
);

create table if not exists public.lubricant_stock_balances (
  storage_id bigint not null references public.lubricant_storages(id) on delete cascade,
  product_id bigint not null references public.lubricant_products(id),
  quantity numeric(14,2) not null default 0 check (quantity >= 0),
  updated_at timestamptz not null default now(),
  primary key(storage_id, product_id)
);

create table if not exists public.lubricant_movements (
  id bigint generated by default as identity primary key,
  request_id uuid not null unique,
  created_at timestamptz not null default now(),
  tanggal date not null default (timezone('Asia/Jakarta',now()))::date,
  movement_type text not null check (movement_type in ('RECEIPT','TRANSFER','USAGE','ADJUSTMENT')),
  product_id bigint not null references public.lubricant_products(id),
  source_storage_id bigint references public.lubricant_storages(id),
  destination_storage_id bigint references public.lubricant_storages(id),
  quantity numeric(14,2) not null check (quantity > 0),
  base_unit text not null check (base_unit in ('L','KG')),
  packaging text,
  package_count numeric(12,2),
  package_size numeric(12,2),
  supplier text,
  document_no text,
  note text,
  source_balance_before numeric(14,2),
  source_balance_after numeric(14,2),
  destination_balance_before numeric(14,2),
  destination_balance_after numeric(14,2),
  created_by uuid,
  created_by_name text,
  created_by_role text
);

create table if not exists public.lubricant_stock_readings (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  tanggal date not null default (timezone('Asia/Jakarta',now()))::date,
  storage_id bigint not null references public.lubricant_storages(id) on delete cascade,
  product_id bigint not null references public.lubricant_products(id),
  reading_type text not null check (reading_type in ('LO_SOUNDING','LUBE_BAR')),
  reading_value numeric(12,2) not null,
  reading_unit text not null check (reading_unit in ('MM','L')),
  physical_quantity numeric(14,2) not null check (physical_quantity >= 0),
  system_quantity numeric(14,2) not null check (system_quantity >= 0),
  variance numeric(14,2) not null,
  note text,
  created_by uuid,
  created_by_name text,
  created_by_role text
);

create index if not exists idx_lubricant_movements_created on public.lubricant_movements(created_at desc);
create index if not exists idx_lubricant_movements_product on public.lubricant_movements(product_id, created_at desc);
create index if not exists idx_lubricant_readings_storage on public.lubricant_stock_readings(storage_id, product_id, created_at desc);

